from __future__ import annotations

SYSTEM_PROMPT = "Ты — внимательный редактор русского языка. Отвечай кратко, понятно и только по запросу пользователя."


def build_style_review_prompt(text: str, style: str) -> str:
	return (
		f"{SYSTEM_PROMPT}\n"
		f"Проверь следующий текст на соответствие стилю «{style}».\n"
		"Текст для проверки:\n"
		f"{text}\n\n"
		"Верни только замечания по тексту: укажи проблемный фрагмент, объясни проблему и предложи исправление. "
		"Оформи замечания маркированным списком. Если замечаний нет, напиши: «Замечаний нет»."
	)
